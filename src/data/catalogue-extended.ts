import type { CatalogueTest, TestDepartment } from "@/types";

function quant(
  id: string,
  name: string,
  department: TestDepartment,
  sampleType: string,
  opts: Partial<CatalogueTest> = {},
): CatalogueTest {
  return {
    id,
    name,
    department,
    sampleType,
    turnaroundTime: opts.turnaroundTime ?? "24 hours",
    price: opts.price ?? 15,
    referenceRange: opts.referenceRange ?? "—",
    units: opts.units ?? "—",
    loincCode: opts.loincCode,
    panelAnalyte: opts.panelAnalyte,
    testKind: opts.testKind,
    resultStyle: opts.resultStyle,
    constituentTestIds: opts.constituentTestIds,
  };
}

function qual(
  id: string,
  name: string,
  department: TestDepartment,
  sampleType: string,
  opts: Partial<CatalogueTest> = {},
): CatalogueTest {
  return quant(id, name, department, sampleType, {
    ...opts,
    resultStyle: "qualitative",
    testKind: "qualitative",
    referenceRange: opts.referenceRange ?? "Non-reactive / Negative",
    units: "—",
  });
}

function mcs(
  id: string,
  name: string,
  sampleType: string,
  price = 32,
): CatalogueTest {
  return quant(id, name, "Microbiology", sampleType, {
    price,
    turnaroundTime: "48–72 hours",
    referenceRange: "See culture report",
    resultStyle: "microbiology_mcs",
    testKind: "microbiology",
  });
}

